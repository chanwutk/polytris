def tolerance_key(threshold_pct: int) -> str:
    """Mistrack-rate tolerance M = 1 - t of a threshold t given in percent, as a JSON key."""
    # Formatting to two decimals keeps keys exact (no 0.19999 from the float division).
    return f'{(100 - threshold_pct) / 100:.2f}'


def gap_key(value: int) -> str:
    """A candidate gap or sampling rate as a zero-padded JSON key, so sorted keys stay in numeric order."""
    # Two digits cover every candidate gap and sampling rate (at most 16).
    return f'{value:02d}'


def load_profile(directory: Path) -> dict:
    """One p016 profile: candidate gaps, counts, accuracy, the cached gap table, its thresholds (percent), and input records."""
    # Every file the measurement reads must exist; a missing one means p016 never ran here.
    assert_files_exist([directory / name for name in ('sample_rates.json', 'counts.npy', 'accuracy.npy', 'max_rate_table.npy')],
                       'p016 profile files (run scripts/p016_tune_track_rate.py)')
    # Candidate gaps, in the order of the counts' first axis.
    gaps = json.loads((directory / 'sample_rates.json').read_text())
    # A gap set must be non-empty integers (not floats or booleans), strictly increasing, and start at the native rate.
    assert isinstance(gaps, list) and gaps and all(type(g) is int for g in gaps) and gaps == sorted(set(gaps)) \
        and gaps[0] == 1, f'{directory}: bad candidate gaps {gaps}'
    # Per-gap, per-tile [correct, incorrect] association counts.
    counts = np.load(directory / 'counts.npy')
    # Exact integer arithmetic below needs integer tallies.
    assert np.issubdtype(counts.dtype, np.integer), f'{directory}: counts dtype {counts.dtype} is not an integer type'
    assert counts.ndim == 4 and counts.shape[0] == len(gaps) and counts.shape[3] == 2, \
        f'{directory}: counts shape {counts.shape} does not match {len(gaps)} gaps'
    assert (counts >= 0).all(), f'{directory}: negative counts'
    # The smoothed accuracy Fig. 7 reads must be p016's float32 formula on these counts.
    accuracy = np.load(directory / 'accuracy.npy')
    correct, incorrect = counts[..., 0].astype(np.float32), counts[..., 1].astype(np.float32)
    assert np.array_equal(accuracy, (correct + 1) / (correct + incorrect + 2)), \
        f'{directory}: accuracy.npy is not (correct + 1) / (total + 2) of counts.npy'
    # The cached per-threshold gap table the ILP read.
    table = np.load(directory / 'max_rate_table.npy')
    # Threshold of each slice, read from the slice file names.
    thresholds = sorted(int(m.group(1)) for p in directory.glob('max_rate_*.txt') if (m := SLICE_FILE.fullmatch(p.name)))
    assert thresholds and all(0 < t <= 100 for t in thresholds), f'{directory}: bad threshold files {thresholds}'
    assert table.shape == (*counts.shape[1:3], len(thresholds)), \
        f'{directory}: table shape {table.shape} does not match grid {counts.shape[1:3]} x {len(thresholds)} thresholds'
    # Every cached gap must be a candidate gap.
    assert np.isin(table, gaps).all(), f'{directory}: table holds gaps outside {gaps}'
    # p016 stores slices in ascending threshold order; each slice file must equal its slice, which confirms it.
    slices = np.stack([np.loadtxt(directory / f'max_rate_{t:03d}.txt', dtype=np.int64, ndmin=2) for t in thresholds], axis=-1)
    assert np.array_equal(slices, table), f'{directory}: max_rate_*.txt files disagree with max_rate_table.npy'
    # Per-video partial counts p016 summed; stale files from an earlier video set would make them disagree.
    partials = sorted((directory / 'partial').glob('*.npy'))
    partial_sum = sum(np.load(p) for p in partials) if partials else None
    return dict(gaps=gaps, counts=counts, accuracy=accuracy, table=table, thresholds=thresholds, inputs=dict(
        directory=str(directory), max_rate_table=file_record(directory / 'max_rate_table.npy'),
        counts=file_record(directory / 'counts.npy'), partial_files=len(partials),
        counts_equal_partial_sum=None if partial_sum is None else bool(np.array_equal(partial_sum, counts))))


def create_tables(con: duckdb.DuckDBPyConnection, profiles: dict[tuple[str, str], dict]):
    """Tables rates (per tile and candidate gap) and tile_gaps (per tile and threshold), and view tile_classes.

    tile_gaps holds the cached gap, the gap recomputed from the counts, the tile's native-rate
    association count and class, the observations behind the chosen gap, and the skipped-gap flag.
    tile_classes repeats every tile_gaps row once more under the class 'all'.
    """
    # A measurement over no profiles has nothing to report.
    assert profiles, 'no p016 profiles to measure'
    rate_frames, gap_frames = [], []
    # Flatten each profile's arrays into long tables (one small profile per dataset and tracker).
    for (dataset, tracker), p in profiles.items():
        counts, table = p['counts'], p['table']
        # Gap index, row, and column of every counts cell, in C order like ravel().
        g, r, c = np.indices(counts.shape[:3]).reshape(3, -1)
        rate_frames.append(pd.DataFrame(dict(
            dataset=dataset, tracker=tracker, row=r, col=c, gap=np.asarray(p['gaps'])[g],
            correct=counts[..., 0].ravel().astype(np.int64), incorrect=counts[..., 1].ravel().astype(np.int64))))
        # Row, column, and threshold index of every table cell.
        r, c, k = np.indices(table.shape).reshape(3, -1)
        gap_frames.append(pd.DataFrame(dict(
            dataset=dataset, tracker=tracker, row=r, col=c,
            threshold_pct=np.asarray(p['thresholds'])[k], gap=table.ravel().astype(np.int64))))
    # Materialize both long tables in DuckDB.
    con.register('rates_df', pd.concat(rate_frames, ignore_index=True))
    con.register('cached_df', pd.concat(gap_frames, ignore_index=True))
    con.execute('CREATE OR REPLACE TABLE rates AS SELECT * FROM rates_df')
    con.execute('CREATE OR REPLACE TABLE cached AS SELECT * FROM cached_df')
    # Per tile and threshold: recompute the gap with exact integers ((c + 1) / (n + 2) >= t / 100),
    # count the observations at the chosen gap, flag skipped smaller gaps, and attach the tile class.
    con.execute("""
        CREATE OR REPLACE TABLE tile_gaps AS
        WITH tiles AS (
            SELECT dataset, tracker, row, col,
                   sum(correct + incorrect) FILTER (WHERE gap = 1) AS associations
            FROM rates GROUP BY dataset, tracker, row, col
        ),
        judged AS (
            SELECT a.dataset, a.tracker, a.row, a.col, a.threshold_pct, a.gap, r.gap AS candidate,
                   r.correct + r.incorrect AS observed,
                   100 * (r.correct + 1) >= a.threshold_pct * (r.correct + r.incorrect + 2) AS meets
            FROM cached a JOIN rates r USING (dataset, tracker, row, col)
        ),
        exact AS (
            SELECT dataset, tracker, row, col, threshold_pct, gap,
                   coalesce(max(candidate) FILTER (WHERE meets), 1) AS exact_gap,
                   count(*) FILTER (WHERE candidate < gap AND NOT meets) > 0 AS skipped_gap,
                   any_value(observed) FILTER (WHERE candidate = gap) AS chosen_observations
            FROM judged GROUP BY dataset, tracker, row, col, threshold_pct, gap
        )
        SELECT e.*, t.associations,
               CASE WHEN t.associations > 0 THEN 'relevant' ELSE 'never_relevant' END AS tile_class
        FROM exact e JOIN tiles t USING (dataset, tracker, row, col)
    """)
    # Every tile once in its own class and once in 'all', shared by the summary and the distribution.
    con.execute("""
        CREATE OR REPLACE VIEW tile_classes AS
        SELECT * FROM tile_gaps
        UNION ALL SELECT * REPLACE ('all' AS tile_class) FROM tile_gaps
    """)


def recompute_mismatches(con: duckdb.DuckDBPyConnection) -> list[dict]:
    """Per dataset, tracker, and threshold, how many tiles' cached gaps differ from the exact rule."""
    return query_dicts(con, """
        SELECT dataset, tracker, threshold_pct, count(*) FILTER (WHERE gap <> exact_gap) AS mismatches
        FROM tile_gaps GROUP BY ALL ORDER BY ALL
    """)


def gap_summary(con: duckdb.DuckDBPyConnection) -> list[dict]:
    """Per dataset, tracker, threshold, and tile class: tile count, gap statistics, kept-fraction floors, flags.

    The floors average over relevant tiles only, so they are NULL for never-relevant tiles and
    equal the relevant tiles' values for 'all'.
    """
    return query_dicts(con, """
        SELECT dataset, tracker, threshold_pct, tile_class, count(*) AS tiles,
               avg(gap) AS mean_gap, quantile_disc(gap, 0.5) AS median_gap,
               avg(1.0::DOUBLE / gap) FILTER (WHERE associations > 0) AS kept_fraction_lower_bound,
               sum(associations / gap) / nullif(sum(associations), 0) AS kept_fraction_lower_bound_weighted,
               count(*) FILTER (WHERE associations > 0 AND gap > 1 AND chosen_observations = 0) AS unobserved_gap_tiles,
               count(*) FILTER (WHERE associations > 0 AND gap > 1 AND chosen_observations < $k) AS few_observation_tiles,
               count(*) FILTER (WHERE skipped_gap) AS skipped_gap_tiles
        FROM tile_classes GROUP BY ALL ORDER BY ALL
    """, {'k': LOW_EVIDENCE_OBSERVATIONS})


def gap_distribution(con: duckdb.DuckDBPyConnection) -> list[dict]:
    """Per dataset, tracker, threshold, and tile class, the tile count and share at every candidate gap (zeros included)."""
    return query_dicts(con, """
        WITH candidates AS (SELECT DISTINCT dataset, tracker, gap FROM rates),
        groups AS (
            SELECT dataset, tracker, threshold_pct, tile_class, count(*) AS group_tiles
            FROM tile_classes GROUP BY ALL
        )
        SELECT g.dataset, g.tracker, g.threshold_pct, g.tile_class, k.gap,
               count(c.gap) AS tiles, count(c.gap) / any_value(g.group_tiles) AS share
        FROM groups g JOIN candidates k USING (dataset, tracker)
        LEFT JOIN tile_classes c ON c.dataset = g.dataset AND c.tracker = g.tracker
                                AND c.threshold_pct = g.threshold_pct AND c.tile_class = g.tile_class AND c.gap = k.gap
        GROUP BY ALL ORDER BY ALL
    """)


def sample_rate_effect(con: duckdb.DuckDBPyConnection, sample_rates: list[int]) -> list[dict]:
    """Per dataset, tracker, threshold, and whole-frame sampling rate s, the gaps p022 hands the ILP on relevant tiles.

    p022 divides each gap by s (floor, at least 1), in units of sampled frames. The result is also
    kept as table sample_rate_effect for the per-setting comparison.
    """
    # Sampling rates must be positive integers for the floor division.
    assert sample_rates and all(type(s) is int and s > 0 for s in sample_rates), f'bad sample rates {sample_rates}'
    con.execute("""
        CREATE OR REPLACE TABLE sample_rate_effect AS
        WITH ilp AS (
            SELECT g.dataset, g.tracker, g.threshold_pct, s.sample_rate, g.associations,
                   greatest(g.gap // s.sample_rate, 1) AS ilp_gap
            FROM tile_gaps g CROSS JOIN (SELECT unnest($rates::INTEGER[]) AS sample_rate) s
            WHERE g.tile_class = 'relevant'
        )
        SELECT dataset, tracker, threshold_pct, sample_rate,
               avg(sample_rate * ilp_gap) AS mean_effective_gap,
               avg(CASE WHEN ilp_gap >= 2 THEN 1 ELSE 0 END) AS prunable_tile_share,
               sum(associations / ilp_gap) / sum(associations) AS kept_fraction_lower_bound_weighted
        FROM ilp GROUP BY ALL
    """, {'rates': sample_rates})
    return query_dicts(con, 'SELECT * FROM sample_rate_effect ORDER BY ALL')


def pipeline_ids(validated: pd.DataFrame) -> pd.DataFrame:
    """`validated` plus the variant id the pipeline builds from each row's parameters (expected_id) and,
    for pruned rows, the 022 directory name (prune_id). Both are None when a parameter is missing or a
    tile size or sampling rate is not an integer, so the consistency check reports the row."""
    # Ids per row, in row order.
    expected, prune = [], []
    # Config rows, not data: a few hundred ids, built with the pipeline's own codec (polyis.utilities).
    for row in validated.itertuples(index=False):
        params = dict(classifier=row.classifier, tilesize=row.tilesize, sample_rate=row.sample_rate,
                      tracker=row.tracker, relevance_threshold=row.relevance_threshold)
        packing = dict(tilepadding=row.tilepadding, canvas_scale=row.canvas_scale)
        # A row with a missing or non-integral parameter has no pipeline id.
        if any(pd.isna(v) for v in (params | packing).values()) \
                or not all(float(params[k]).is_integer() for k in ('tilesize', 'sample_rate')):
            expected.append(None)
            prune.append(None)
            continue
        # Integer tile size and sampling rate, float thresholds, as p022 and p130 pass them.
        params.update(tilesize=int(params['tilesize']), sample_rate=int(params['sample_rate']),
                      relevance_threshold=float(params['relevance_threshold']))
        threshold = None if pd.isna(row.tracking_accuracy_threshold) else float(row.tracking_accuracy_threshold)
        expected.append(build_param_str(**params, **packing, tracking_accuracy_threshold=threshold))
        # Packing settings do not enter the 022 directory name, so padding variants share one pruning setting.
        prune.append(None if threshold is None else build_param_str(**params, tracking_accuracy_threshold=threshold))
    return validated.assign(expected_id=pd.Series(expected, index=validated.index, dtype=object),
                            prune_id=pd.Series(prune, index=validated.index, dtype=object))


def validated_configs(con: duckdb.DuckDBPyConnection, validated: pd.DataFrame, tile_size: int,
                      thresholds: dict[tuple[str, str], list[int]]) -> tuple[list[dict], int]:
    """Per dataset, tracker, threshold (None for no pruning), and sampling rate: validated rows and distinct pruning settings.

    `validated` has the VALIDATED_COLUMNS (threshold NaN or None for no pruning). Every row's variant
    id must equal the id the pipeline builds from its parameters, which checks threshold, sampling
    rate, tracker, tile size, relevance threshold, and packing settings at once. Rows of other tile
    sizes are dropped and counted (the second return value). A pruned row of a measured profile must
    use a threshold that profile stores. Leaves tables validated_tile and profile_thresholds.
    """
    # Make the configurations, with their pipeline ids, queryable.
    con.register('validated_df', pipeline_ids(validated))
    con.execute("""
        CREATE OR REPLACE TABLE validated_pct AS
        SELECT *, CASE WHEN tracking_accuracy_threshold IS NULL OR isnan(tracking_accuracy_threshold) THEN NULL
                       ELSE CAST(round(tracking_accuracy_threshold * 100) AS INTEGER) END AS threshold_pct
        FROM validated_df
    """)
    # Thresholds each measured profile stores.
    con.register('profile_thresholds_df', pd.DataFrame(
        [(d, t, pct) for (d, t), pcts in thresholds.items() for pct in pcts],
        columns=['dataset', 'tracker', 'threshold_pct']).astype({'threshold_pct': 'int64'}))
    con.execute('CREATE OR REPLACE TABLE profile_thresholds AS SELECT * FROM profile_thresholds_df')
    # Every row's id must be the one its parameters build (NULL-safe, so a missing parameter fails too).
    bad = query_dicts(con, 'SELECT variant_id FROM validated_pct WHERE expected_id IS DISTINCT FROM variant_id')
    assert not bad, f'validated configurations disagree with the ids the pipeline builds from their parameters: {bad}'
    # Only rows of the profiles' tile size are measured; the others are counted.
    other_tile_rows = con.execute('SELECT count(*) FROM validated_pct WHERE tilesize <> $tile', {'tile': tile_size}).fetchone()[0]
    con.execute('CREATE OR REPLACE TABLE validated_tile AS SELECT * FROM validated_pct WHERE tilesize = $tile',
                {'tile': tile_size})
    # A pruned row of a measured profile must use a threshold that profile stores (p022 indexes the table by it).
    unknown = query_dicts(con, """
        SELECT DISTINCT v.dataset, v.tracker, v.threshold_pct FROM validated_tile v
        SEMI JOIN profile_thresholds m ON m.dataset = v.dataset AND m.tracker = v.tracker
        ANTI JOIN profile_thresholds p ON p.dataset = v.dataset AND p.tracker = v.tracker AND p.threshold_pct = v.threshold_pct
        WHERE v.threshold_pct IS NOT NULL ORDER BY ALL
    """)
    assert not unknown, f'validated thresholds missing from the p016 profiles: {unknown}'
    rows = query_dicts(con, """
        SELECT dataset, tracker, threshold_pct, CAST(sample_rate AS INTEGER) AS sample_rate, count(*) AS configs,
               count(DISTINCT prune_id) AS pruning_settings
        FROM validated_tile GROUP BY ALL ORDER BY ALL
    """)
    return rows, other_tile_rows


def validated_totals(con: duckdb.DuckDBPyConnection) -> list[dict]:
    """Over the measured profiles, validated rows and distinct pruning settings per kind (pruned or none) and sampling rate."""
    return query_dicts(con, """
        SELECT CASE WHEN threshold_pct IS NULL THEN 'none' ELSE 'pruned' END AS kind,
               CAST(sample_rate AS INTEGER) AS sample_rate, count(*) AS configs,
               count(DISTINCT dataset || '/' || prune_id) AS pruning_settings
        FROM validated_tile v SEMI JOIN profile_thresholds m ON m.dataset = v.dataset AND m.tracker = v.tracker
        GROUP BY ALL ORDER BY ALL
    """)


def pruning_settings(con: duckdb.DuckDBPyConnection) -> list[dict]:
    """Distinct validated pruning settings of the measured profiles, with the number of validated rows sharing each."""
    return query_dicts(con, """
        SELECT v.dataset, v.tracker, v.classifier, CAST(v.tilesize AS INTEGER) AS tilesize,
               CAST(v.sample_rate AS INTEGER) AS sample_rate, v.threshold_pct, v.relevance_threshold, v.prune_id,
               count(*) AS configs
        FROM validated_tile v SEMI JOIN profile_thresholds m ON m.dataset = v.dataset AND m.tracker = v.tracker
        WHERE v.prune_id IS NOT NULL GROUP BY ALL ORDER BY ALL
    """)


def list_test_videos(dataset: str) -> list[str]:
    """The dataset's test videos, listed as p022 lists them; fails on a missing or empty videoset."""
    # The videoset directory p022 iterates.
    videos = list_split_videos(dataset, 'test')
    # A measured kept fraction over no videos would be empty.
    assert videos, f'{dataset}: no test videos'
    return videos


def kept_counts(dataset: str, settings: list[dict], profiles: dict, videos: list[str]) -> list[dict]:
    """Per pruning setting and test video: the ILP's input and kept tile-frames, from the cached 020 and 022 outputs.

    Every setting must have a 022 output on every video with the same frames as its 020 input.
    covered is the input under PRUNE_RULE, covered_current_rule the input under the current p022
    rule, kept_outside the kept tile-frames outside the input (0 when PRUNE_RULE is the rule the
    output was made with), and bound_tile_frames the sum over tiles of covered / (gap // s).
    """
    # One row per setting and test video.
    rows = []
    # Files are read per video so each 020 input is decoded once for all settings sharing it.
    for video in videos:
        # Decoded 020 inputs of this video, by (classifier, tile size, sampling rate).
        scores: dict[tuple, tuple[np.ndarray, list[int]]] = {}
        for s in settings:
            source = (s['classifier'], s['tilesize'], s['sample_rate'])
            # Classifier scores of this video at the setting's sampling rate (p022's input file).
            if source not in scores:
                scores[source] = decode_grids(load_classification_results(
                    dataset, video, s['tilesize'], s['classifier'], s['sample_rate']))
            # The setting's ILP input scores and their frame indices.
            grids, frame_idx = scores[source]
            # p022's saved selection; it must cover the same frames and tile grid.
            pruned, pruned_idx = decode_grids(load_pruned_classification_results(
                dataset, video, s['tilesize'], s['classifier'], s['tracker'], s['threshold_pct'] / 100,
                s['relevance_threshold'], s['sample_rate']))
            assert pruned_idx == frame_idx and pruned.shape == grids.shape, \
                f"{dataset} {video} {s['prune_id']}: 022 frames or grid differ from 020"
            # The setting's profile must cover the same tile grid.
            profile = profiles[(dataset, s['tracker'])]
            assert grids.shape[1:] == profile['table'].shape[:2], \
                f"{dataset} {video}: grid {grids.shape[1:]} differs from the profile's {profile['table'].shape[:2]}"
            # The gaps p022 handed this ILP, in sampled frames.
            ilp_gap = np.maximum(profile['table'][..., profile['thresholds'].index(s['threshold_pct'])] // s['sample_rate'], 1)
            # ILP input under the cached outputs' rule, and kept tiles.
            covered = RELEVANCE_RULES[PRUNE_RULE](grids, s['relevance_threshold'])
            kept = pruned > 0
            # File versions, to check that each input predates the output that read it.
            score_path = cache.exec(dataset, 'relevancy', video, '_'.join(map(str, source)), 'score', 'score.jsonl')
            pruned_path = cache.exec(dataset, 'pruned-polyominoes', video, s['prune_id'], 'score', 'score.jsonl')
            # Input, kept, and floor tile-frame counts of this setting on this video.
            rows.append(dict(
                dataset=dataset, prune_id=s['prune_id'], video=video, frames=grids.shape[0],
                tiles=grids.shape[1] * grids.shape[2], covered=int(covered.sum()),
                covered_current_rule=int(RELEVANCE_RULES['current'](grids, s['relevance_threshold']).sum()),
                kept=int(kept.sum()), kept_outside=int((kept & ~covered).sum()),
                bound_tile_frames=float((covered.sum(axis=0) / ilp_gap).sum()),
                relevancy_mtime=iso_utc(os.path.getmtime(score_path)), pruned_mtime=iso_utc(os.path.getmtime(pruned_path))))
    return rows


def kept_summary(con: duckdb.DuckDBPyConnection, counts: list[dict], settings: list[dict]) -> tuple[list, list, list]:
    """Measured kept fractions per pruning setting, per (dataset, tracker, threshold, sampling rate), and input timing per profile.

    Needs table sample_rate_effect. kept_fraction = kept / covered over the test videos; the
    floor at the same s is given weighted by training associations (from the profile) and by the
    test input itself (bound_test_weighted), so that the floor's looseness can be told from its weights.
    """
    # Without validated pruning settings there is nothing measured.
    if not settings:
        return [], [], []
    # Make the settings and the per-video counts queryable.
    con.register('settings_df', pd.DataFrame(settings))
    con.register('kept_df', pd.DataFrame(counts))
    con.execute('CREATE OR REPLACE TABLE pruning_setting AS SELECT * FROM settings_df')
    con.execute('CREATE OR REPLACE TABLE kept_counts AS SELECT * FROM kept_df')
    # Totals per setting over its test videos.
    con.execute("""
        CREATE OR REPLACE TABLE setting_kept AS
        SELECT s.dataset, s.tracker, s.threshold_pct, s.sample_rate, s.relevance_threshold, s.prune_id, s.configs,
               count(*) AS videos, sum(k.frames) AS frames, sum(k.frames * k.tiles) AS tile_frames,
               sum(k.covered) AS covered, sum(k.covered_current_rule) AS covered_current_rule,
               sum(k.kept) AS kept, sum(k.kept_outside) AS kept_outside, sum(k.bound_tile_frames) AS bound_tile_frames,
               sum(k.kept) / nullif(sum(k.covered), 0) AS kept_fraction,
               sum(k.bound_tile_frames) / nullif(sum(k.covered), 0) AS bound_test_weighted,
               sum(k.covered) / nullif(sum(k.frames * k.tiles), 0) AS covered_share,
               min(k.pruned_mtime) AS earliest_pruned_output, max(k.relevancy_mtime) AS latest_relevancy_input,
               count(*) FILTER (WHERE k.relevancy_mtime > k.pruned_mtime) AS relevancy_newer_than_pruned
        FROM pruning_setting s JOIN kept_counts k USING (dataset, prune_id)
        GROUP BY ALL
    """)
    # Every setting must have been measured on at least one video.
    missing = query_dicts(con, 'SELECT prune_id FROM pruning_setting ANTI JOIN setting_kept USING (dataset, prune_id)')
    assert not missing, f'pruning settings without measured videos: {missing}'
    # Per setting, next to the training-weighted floor at the same threshold and rate.
    per_setting = query_dicts(con, """
        SELECT k.*, e.kept_fraction_lower_bound_weighted AS bound_train_weighted
        FROM setting_kept k LEFT JOIN sample_rate_effect e USING (dataset, tracker, threshold_pct, sample_rate)
        ORDER BY ALL
    """)
    # Pooled per threshold and sampling rate, with the range over settings.
    per_rate = query_dicts(con, """
        SELECT dataset, tracker, threshold_pct, sample_rate, count(*) AS settings, sum(configs) AS configs,
               sum(kept) / nullif(sum(covered), 0) AS kept_fraction,
               min(kept_fraction) AS kept_fraction_min, max(kept_fraction) AS kept_fraction_max,
               sum(bound_tile_frames) / nullif(sum(covered), 0) AS bound_test_weighted,
               sum(covered) / nullif(sum(tile_frames), 0) AS covered_share, sum(kept_outside) AS kept_outside
        FROM setting_kept GROUP BY ALL ORDER BY ALL
    """)
    # Per profile: input timing, kept tile-frames outside the input, and the current rule's share of it.
    per_profile = query_dicts(con, """
        SELECT dataset, tracker, min(earliest_pruned_output) AS earliest_pruned_output,
               max(latest_relevancy_input) AS latest_relevancy_input,
               sum(relevancy_newer_than_pruned) AS relevancy_newer_than_pruned, sum(kept_outside) AS kept_outside,
               sum(covered_current_rule) / nullif(sum(covered), 0) AS covered_current_rule_share
        FROM setting_kept GROUP BY ALL ORDER BY ALL
    """)
    return per_setting, per_rate, per_profile


def figure_crop(profile: dict, rows: tuple[int, int], cols: tuple[int, int]) -> dict:
    """The cached gaps and smoothed mistrack rates (percent) on a tile crop, computed as the figure script does.

    The figure reads accuracy.npy and prints round(100 * (1 - accuracy)), half to even, which np.round matches.
    """
    # The arrays the figure reads (accuracy) and the ILP reads (table).
    accuracy, table = profile['accuracy'], profile['table']
    # The crop must lie inside the tile grid.
    assert 0 <= rows[0] < rows[1] <= table.shape[0] and 0 <= cols[0] < cols[1] <= table.shape[1], \
        f'crop rows {rows} cols {cols} outside grid {table.shape[:2]}'
    # Smoothed mistrack rate 1 - accuracy per gap on the crop, in float64 like the figure's Python floats.
    mistrack = 1 - accuracy[:, rows[0]:rows[1], cols[0]:cols[1]].astype(np.float64)
    return dict(
        rows=list(rows), cols=list(cols),
        mistrack_pct={gap_key(g): np.round(100 * mistrack[i]).astype(int).tolist() for i, g in enumerate(profile['gaps'])},
        gaps_by_tolerance={tolerance_key(t): table[rows[0]:rows[1], cols[0]:cols[1], k].tolist()
                           for k, t in enumerate(profile['thresholds'])})


def assemble(profiles: dict, summary: list[dict], distribution: list[dict], effect: list[dict],
             configs: list[dict], mismatches: list[dict], kept_rates: list[dict] = (),
             kept_profiles: list[dict] = ()) -> tuple[dict, list[dict]]:
    """Arrange the query results as {dataset: {trackers: {tracker: report}}} and as flat table rows."""
    # Nested report, filled per profile below.
    report: dict = {}
    # One entry per profile, with its grid, inputs, and every threshold filled in below.
    for (dataset, tracker), p in profiles.items():
        report.setdefault(dataset, dict(label=DATASET_LABELS.get(dataset, dataset), trackers={}))
        report[dataset]['trackers'][tracker] = dict(
            figure_7=(dataset, tracker) == (FIGURE_7['dataset'], FIGURE_7['tracker']),
            grid=list(p['table'].shape[:2]), candidate_gaps=p['gaps'], recompute_mismatches=0,
            inputs=dict(p.get('inputs', {})), validated_configs={}, tolerances={
                tolerance_key(t): dict(tracking_accuracy_threshold=t / 100, mistrack_tolerance=(100 - t) / 100,
                                       validated_configs=0, validated_pruning_settings=0, validated_sample_rates={},
                                       with_sample_rate={})
                for t in p['thresholds']})

    def entry_of(r: dict) -> dict:
        # The profile entry a query row belongs to.
        return report[r['dataset']]['trackers'][r['tracker']]

    def level_of(r: dict) -> dict:
        # The threshold entry a query row belongs to.
        return entry_of(r)['tolerances'][tolerance_key(r['threshold_pct'])]

    # Cached-versus-recomputed gap differences, summed per profile and listed per threshold.
    for r in mismatches:
        entry_of(r)['recompute_mismatches'] += r['mismatches']
        level_of(r)['recompute_mismatches'] = r['mismatches']
    # Gap statistics per tile class.
    for r in summary:
        level_of(r)[r['tile_class']] = {k: rounded(r[k]) for k in (
            'tiles', 'mean_gap', 'median_gap', 'kept_fraction_lower_bound', 'kept_fraction_lower_bound_weighted',
            'unobserved_gap_tiles', 'few_observation_tiles', 'skipped_gap_tiles')} | dict(gap_share={}, gap_tiles={})
    # Share and count of each class's tiles at every candidate gap.
    for r in distribution:
        level = level_of(r)[r['tile_class']]
        level['gap_share'][gap_key(r['gap'])] = rounded(r['share'])
        level['gap_tiles'][gap_key(r['gap'])] = r['tiles']
    # The gaps the ILP sees under each whole-frame sampling rate.
    for r in effect:
        level_of(r)['with_sample_rate'][gap_key(r['sample_rate'])] = {k: rounded(r[k]) for k in (
            'mean_effective_gap', 'prunable_tile_share', 'kept_fraction_lower_bound_weighted')}
    # Measured kept fractions of the validated pruning settings, next to the floor at the same rate.
    for r in kept_rates:
        level_of(r)['with_sample_rate'].setdefault(gap_key(r['sample_rate']), {})['measured'] = {k: rounded(r[k]) for k in (
            'settings', 'configs', 'kept_fraction', 'kept_fraction_min', 'kept_fraction_max', 'bound_test_weighted',
            'covered_share', 'kept_outside')}
    # Input timing per profile: the profile must predate the ILP outputs that read it.
    for r in kept_profiles:
        inputs = entry_of(r)['inputs']
        inputs.update({k: rounded(r[k]) for k in ('earliest_pruned_output', 'latest_relevancy_input',
                                                   'relevancy_newer_than_pruned', 'kept_outside',
                                                   'covered_current_rule_share')})
        if 'max_rate_table' in inputs:
            inputs['profile_predates_pruning'] = inputs['max_rate_table']['mtime'] < r['earliest_pruned_output']
    # Validated configurations, per threshold (or "none") and sampling rate.
    for r in configs:
        entry = report.get(r['dataset'], {}).get('trackers', {}).get(r['tracker'])
        # Configurations of trackers or datasets outside the measured profiles are not reported.
        if entry is None:
            continue
        key = 'none' if r['threshold_pct'] is None else tolerance_key(r['threshold_pct'])
        entry['validated_configs'].setdefault(key, {})[gap_key(r['sample_rate'])] = r['configs']
        if key != 'none':
            level = level_of(r)
            level['validated_configs'] += r['configs']
            level['validated_pruning_settings'] += r['pruning_settings']
            level['validated_sample_rates'][gap_key(r['sample_rate'])] = r['configs']
    # Flat rows: one per dataset, tracker, threshold, and tile class, with gap shares as columns.
    rows = [dict(dataset=dataset, label=d['label'], tracker=tracker, figure_7=e['figure_7'],
                 tracking_accuracy_threshold=level['tracking_accuracy_threshold'],
                 mistrack_tolerance=level['mistrack_tolerance'], validated_configs=level['validated_configs'],
                 validated_pruning_settings=level['validated_pruning_settings'],
                 tile_class=cls, **{k: v for k, v in level[cls].items() if k not in ('gap_share', 'gap_tiles')},
                 **{f'share_gap_{g}': s for g, s in level[cls]['gap_share'].items()})
            for dataset, d in report.items() for tracker, e in d['trackers'].items()
            for level in e['tolerances'].values() for cls in TILE_CLASSES if cls in level]
    return report, rows


def print_report(report: dict):
    """One line per dataset, tracker, and tolerance (relevant tiles' gap shares, mean gap, floor), then measured kept fractions."""
    # One block per dataset and tracker.
    for dataset, d in report.items():
        for tracker, e in d['trackers'].items():
            # Header: grid, the recompute check, and the validated configurations per tolerance and rate.
            mark = '  (Fig. 7)' if e['figure_7'] else ''
            print(f"\n{d['label']} ({dataset}) {tracker}{mark}: grid {e['grid']}, "
                  f"recompute mismatches {e['recompute_mismatches']}, validated {e['validated_configs']}")
            # One line per tolerance, in increasing M.
            for key, level in sorted(e['tolerances'].items()):
                rel = level.get('relevant')
                # A profile without relevant tiles has nothing to show per gap.
                if rel is None:
                    continue
                # Relevant tiles' share at each candidate gap, and the validated use of this tolerance.
                shares = ' '.join(f"{int(g)}:{s:.2f}" for g, s in sorted(rel['gap_share'].items()))
                used = (f"  <- {level['validated_configs']} rows / {level['validated_pruning_settings']} settings"
                        if level['validated_configs'] else '')
                print(f"  M={key} (t={level['tracking_accuracy_threshold']:.2f}) relevant {rel['tiles']:3d} | {shares} | "
                      f"mean {rel['mean_gap']:.2f} median {rel['median_gap']} floor {rel['kept_fraction_lower_bound_weighted']:.3f}"
                      f" | few-obs {rel['few_observation_tiles']} unobserved {rel['unobserved_gap_tiles']}{used}")
                # Measured kept fractions at each sampling rate with validated settings.
                for rate, effect in sorted(level['with_sample_rate'].items()):
                    m = effect.get('measured')
                    if m:
                        # The training-weighted floor exists only for rates in SAMPLE_RATES.
                        floor = effect.get('kept_fraction_lower_bound_weighted')
                        floor = 'n/a' if floor is None else f'{floor:.3f}'
                        print(f"      s={int(rate):2d}: kept {m['kept_fraction']:.3f} "
                              f"[{m['kept_fraction_min']:.3f}, {m['kept_fraction_max']:.3f}] over {m['settings']} settings; "
                              f"floor {floor} (test-weighted {m['bound_test_weighted']:.3f})")


def main(args):
    # Only the paper's datasets have labels and tradeoff tables.
    unknown = sorted(set(args.datasets) - set(DATASET_LABELS))
    assert not unknown, f'unknown datasets {unknown}; choose from {list(DATASET_LABELS)}'
    # Load every requested profile; a missing one fails with the p016 hint.
    profiles = {(dataset, tracker): load_profile(Path(cache.index(dataset, 'track_rates', f'{tracker}_{args.tile_size}')))
                for dataset in args.datasets for tracker in args.trackers}
    # In-memory DuckDB for all analysis.
    con = duckdb.connect()
    # Long tables and per-tile gaps for all profiles.
    create_tables(con, profiles)
    # Cached gaps against the exact rule, per profile and threshold.
    mismatches = recompute_mismatches(con)
    # Everything below reads the cached gaps as the rule's output, so any disagreement stops the run.
    differing = [r for r in mismatches if r['mismatches']]
    assert not differing, f'cached gaps differ from the exact rule: {differing}'
    # Validated configurations from each dataset's test-split tradeoff table.
    validated = pd.concat([load_test_tradeoff(dataset)[0].assign(dataset=dataset)[VALIDATED_COLUMNS]
                           for dataset in args.datasets], ignore_index=True)
    configs, other_tile_rows = validated_configs(con, validated, args.tile_size,
                                                 {key: p['thresholds'] for key, p in profiles.items()})
    # Gap statistics, gap distribution, and the gaps the ILP sees at each sampling rate.
    summary, distribution = gap_summary(con), gap_distribution(con)
    effect = sample_rate_effect(con, SAMPLE_RATES)
    # Measured kept fractions of every validated pruning setting, over each dataset's test videos.
    settings = pruning_settings(con)
    counts = [row for dataset in args.datasets if any(s['dataset'] == dataset for s in settings)
              for row in kept_counts(dataset, [s for s in settings if s['dataset'] == dataset], profiles, list_test_videos(dataset))]
    per_setting, per_rate, per_profile = kept_summary(con, counts, settings)
    # Arrange everything per dataset and tracker, and as flat rows.
    report, rows = assemble(profiles, summary, distribution, effect, configs, mismatches, per_rate, per_profile)
    # The Fig. 7 crop, so the figure's matrices can be checked against the cached table.
    figure_key = (FIGURE_7['dataset'], FIGURE_7['tracker'])
    figure = dict(FIGURE_7, rows=list(FIGURE_7['rows']), cols=list(FIGURE_7['cols']),
                  label=DATASET_LABELS[FIGURE_7['dataset']])
    if figure_key in profiles:
        figure['crop'] = figure_crop(profiles[figure_key], FIGURE_7['rows'], FIGURE_7['cols'])
    # Tradeoff tables read, with their versions.
    totals = validated_totals(con)
    tradeoffs = {dataset: file_record(Path(cache.eval(dataset, 'tradeoff', 'tradeoff.csv'))) for dataset in args.datasets}
    # Write the nested report with its method notes and input records.
    out = results_dir(__file__)
    write_json(out, 'gap_tolerance.json', dict(
        method=dict(
            rule='gap = largest candidate gap with (correct + 1) / (total + 2) >= t, else 1; mistrack tolerance '
                 'M = 1 - t (paper: largest gap with smoothed MissRate <= M). total is correct + incorrect '
                 'associations counted at the frames gap gamma samples (about 1/gamma of the native-rate count), '
                 'not the native-rate TotalA of §6.2',
            relevant_tile='at least one reference-track association at the native rate on the training videos',
            kept_fraction_lower_bound='ESTIMATE: mean over relevant tiles of 1 / gap, an analytical floor on the '
                                      "fraction of a tile's ILP-input tile-frames the ILP keeps; it holds for tiles "
                                      'covered in at least two sampled frames of a video (a tile covered once is '
                                      'unconstrained and may be dropped); NULL for never-relevant tiles',
            kept_fraction_lower_bound_weighted='ESTIMATE: the same floor weighted by native-rate association counts '
                                               '(box-weighted proxy for relevant tile-frames)',
            with_sample_rate='p022 divides each gap by the whole-frame sampling rate s (floor, at least 1); '
                             'effective gap s * max(gap // s, 1) frames; floor over sampled frames',
            measured='MEASURED on the test split, per validated pruning setting: kept tile-frames in '
                     '022_pruned_polyominoes over ILP-input tile-frames (020_relevancy scores >= floor(T_r * 255), the '
                     'rule the cached outputs follow; kept_outside counts kept tile-frames outside it), summed over '
                     'test videos; kept_fraction pools settings, min/max range over them; bound_test_weighted is the '
                     '1 / (gap // s) floor weighted by the same test input; covered_share is input over all '
                     'classified tile-frames',
            unobserved_gap_tiles='relevant tiles whose gap (> 1) has no observations at that gap (rate is the 0.5 prior)',
            few_observation_tiles=f'relevant tiles whose gap (> 1) has fewer than {LOW_EVIDENCE_OBSERVATIONS} '
                                  'observations at that gap (includes unobserved_gap_tiles)',
            skipped_gap_tiles='tiles whose gap is above a smaller candidate gap that misses the tolerance',
            median_gap='lower median (quantile_disc), always a candidate gap',
            validated_configs='Tetris rows of the test-split tradeoff table (evaluation/090_tradeoff/tradeoff.csv); '
                              'rows include tile-padding and canvas-scale variants, which share one pruning setting '
                              '(validated_pruning_settings counts distinct 022 settings)',
            keys='gap and sampling-rate keys are zero-padded ("01" ... "16"); tolerance keys are M = 1 - t'),
        inputs=dict(profiles='{cache}/{dataset}/indexing/track_rate/{tracker}_' + str(args.tile_size),
                    datasets=args.datasets, trackers=args.trackers, tile_size=args.tile_size,
                    sample_rates=SAMPLE_RATES, tradeoff_tables=tradeoffs,
                    validated_rows_other_tile_sizes=other_tile_rows, prune_rule=PRUNE_RULE),
        validated_totals=totals, figure_7=figure, datasets=report))
    # Flat rows for a plot or table, and one row per validated pruning setting.
    write_json(out, 'table_rows.json', rows)
    write_json(out, 'pruning_settings.json', [
        rounded(r) | dict(label=DATASET_LABELS[r['dataset']], mistrack_tolerance=(100 - r['threshold_pct']) / 100)
        for r in per_setting])
    # Human-readable summary for the run log.
    print_report(report)
    print('\nvalidated totals:', totals)


if __name__ == '__main__':
    main(parse_args())
