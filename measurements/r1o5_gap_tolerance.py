#!/usr/local/bin/python
"""R1.O5: how the mistrack-rate tolerance sets the per-tile maximum sampling gaps (Fig. 7 as a table or curve).

Fig. 7 of the submission (content/06_offline.tex, label fig:missrate-to-g) shows the mapping on a
3 x 4 tile crop of B3D4 (jnc7) with ByteTrack. It is generated by
tetris-paper/scripts/generate_missrate_mapping_figure.py from the cached p016 profile
jnc7/indexing/track_rate/bytetrackcython_60, the same files read here.

Inputs, per dataset and tracker, are the cached outputs of scripts/p016_tune_track_rate.py in
{cache}/{dataset}/indexing/track_rate/{tracker}_{tile}/:
  sample_rates.json    the candidate gaps Gamma = [1, 2, 4, 8, 16]
  counts.npy           (gaps, H, W, 2) integer [correct, incorrect] associations of the reference
                       tracks on the training videos, counted at the frames each gap samples
                       (checked against the sum of partial/*.npy, recorded per profile)
  accuracy.npy         (gaps, H, W) float32 (correct + 1) / (total + 2), which Fig. 7 reads
                       (checked to equal p016's formula on counts.npy)
  max_rate_table.npy   (H, W, thresholds) int32, the maximum gap per tile at each threshold;
                       p022 hands one slice of it, divided by the whole-frame sampling rate,
                       to the ILP
  max_rate_XXX.txt     one slice per threshold XXX (percent); the file names fix the slice order
The tracking accuracy threshold t of a configuration (tracking_accuracy_threshold in the tradeoff
tables, the 3-digit token in variant ids) selects the slice. A tile's gap is the largest candidate
gap whose Laplace-smoothed accuracy (correct + 1) / (total + 2) is at least t, or 1 if none is.
That is the paper's rule with mistrack-rate tolerance M = 1 - t, since the smoothed mistrack rate
is 1 minus the smoothed accuracy. Its denominator is the associations counted at the frames gap
gamma samples (about 1/gamma of the native-rate count), not the native-rate TotalA of §6.2. The
gaps are recomputed here from counts.npy with exact integer arithmetic and must equal the cache.

Measured, per dataset, tracker, and threshold (every threshold p016 stored):
  - the share of tiles at each candidate gap, separately for relevant tiles (at least one
    reference-track association on the training videos at the native rate) and never-relevant
    tiles (none; their smoothed mistrack rate is 0.5 at every gap, so they get gap 16 when
    M >= 0.5 and gap 1 otherwise), plus the mean and the lower median gap;
  - an analytical floor 1 / gap on the fraction of a relevant tile's ILP-input tile-frames the
    ILP keeps, averaged over relevant tiles, unweighted and weighted by native-rate association
    counts (a box-weighted proxy for relevant tile-frames). The ILP forces a tile's first and
    last covered frames and keeps covered frames at most gap apart, so the floor holds for a tile
    covered in at least two sampled frames of a video; a tile covered once is unconstrained.
    It is an estimate implied by the gaps and is several times below what the ILP keeps;
  - the same floor under each whole-frame sampling rate s, since p022 divides gaps by s
    (gap // s, at least 1, in sampled frames), and the share of relevant tiles that the ILP can
    still prune beyond s (gap // s >= 2);
  - the measured kept fraction of every validated pruning setting: tile-frames kept in
    022_pruned_polyominoes over the ILP's input tile-frames, from 020_relevancy binarized at the
    setting's T_r, summed over the test videos. The cached test outputs follow the rule
    score >= floor(T_r * 255) (common.RELEVANCE_RULES 'floor', see measurements/r9o3_ilp_instance_sizes.py), not the
    current p022's score > T_r * 255, and no kept tile-frame falls outside it (kept_outside);
  - diagnostics: relevant tiles whose gap (> 1) rests on no observations at that gap (its rate
    is the 0.5 prior) or on fewer than LOW_EVIDENCE_OBSERVATIONS, and tiles whose gap skips a
    smaller gap that misses the tolerance.
Validated configurations are the Tetris rows of each dataset's test-split tradeoff table, which
include tile-padding and canvas-scale variants that share one pruning setting. Their thresholds,
trackers (pruning uses the tracking tracker's profile, see scripts/p060_exec_track.py), and
whole-frame sampling rates are counted per threshold, as rows and as distinct pruning settings.

Writes measurements-results/r1o5_gap_tolerance/:
  gap_tolerance.json     per dataset and tracker, every threshold's gap distribution, floors,
                         measured kept fractions, diagnostics, validated-configuration counts,
                         input file records, and the Fig. 7 crop
  table_rows.json        the gap summaries as flat rows (one per dataset, tracker, threshold, and
                         tile class) for a plot or a LaTeX table
  pruning_settings.json  one flat row per validated pruning setting with its measured kept fraction
Gap and sampling-rate keys are zero-padded ('01' ... '16') so that sorted JSON keys stay in order.
"""
