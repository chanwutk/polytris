"""Export R1.O3 resolution-scaling macros and table rows from the saved max-batch sweeps.

Source: measurements-results/r1o3_resolution_scaling/summary.json,
section measured_max_batch. The reference detector and the relevance classifier each run on frames with 1x, 2x, and
4x the dataset's pixels, the detector at the frame's own resolution and the classifier on every tile, each at the
largest batch the GPU holds.
Run on the host: python scripts/generate_resolution_scaling.py
"""
import json
from pathlib import Path


root = Path(__file__).resolve().parents[1]
source = root.parent / 'measurements-results/r1o3_resolution_scaling/summary.json'
out = root / 'figures/generated'
# Table order and the short labels used in the response's other tables.
LABELS = {'Amsterdam': 'Ams.', 'CalDoT1': 'CDoT1', 'CalDoT2': 'CDoT2', 'B3D1': 'B3D'}
SCALES = (1, 2, 4)

rows = json.loads(source.read_text())['measured_max_batch']
# One row per dataset and scale.
assert sorted((r['label'], r['scale']) for r in rows) == sorted((l, s) for l in LABELS for s in SCALES)
by = {(r['label'], r['scale']): r for r in rows}


def g(label, scale, field):
    # Growth of a time over the dataset's own frame size (computed in the summary).
    return by[(label, scale)][field]


# Table rows: detection-time and classification-time growth at 2x and 4x the pixels, then their quotient.
lines = [' & '.join([LABELS[l]]
                    + [f'{g(l, s, f):.2f}$\\times$' for f in ('detector_growth', 'classifier_growth') for s in (2, 4)]
                    + [f"{g(l, s, 'classifier_growth') / g(l, s, 'detector_growth'):.2f}" for s in (2, 4)])
         + r' \\' for l in LABELS]
(out / 'revision_resolution_scaling_rows.tex').write_text('\n'.join(lines) + '\n')


def span(field, scale=None):
    # Min and max of a field over datasets (at one scale, or over every scale).
    xs = [r[field] for r in rows if scale is None or r['scale'] == scale]
    return min(xs), max(xs)


numbers = {}
for name, (field, scale, digits) in dict(
        DetectorTwo=('detector_growth', 2, 2), DetectorFour=('detector_growth', 4, 2),
        ClassifierTwo=('classifier_growth', 2, 2), ClassifierFour=('classifier_growth', 4, 2),
        Ratio=('detector_over_classifier', None, 1)).items():
    lo, hi = span(field, scale)
    numbers[f'revisionResolution{name}Min'] = f'{lo:.{digits}f}'
    numbers[f'revisionResolution{name}Max'] = f'{hi:.{digits}f}'
(out / 'revision_resolution_scaling_macros.tex').write_text(
    '% Auto-generated by scripts/generate_resolution_scaling.py from saved measurement exports.\n'
    + ''.join(f'\\newcommand{{\\{k}}}{{\\autogen{{{v}}}}}\n' for k, v in numbers.items()))
print('\n'.join(lines), numbers, sep='\n')
